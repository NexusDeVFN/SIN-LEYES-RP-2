CREATE TABLE IF NOT EXISTS nx_players (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 license VARCHAR(80) NOT NULL UNIQUE,
 firstname VARCHAR(40) NOT NULL DEFAULT 'Ciudadano',
 lastname VARCHAR(40) NOT NULL DEFAULT 'Nuevo',
 cash INT UNSIGNED NOT NULL DEFAULT 500,
 bank INT UNSIGNED NOT NULL DEFAULT 2500,
 job VARCHAR(50) NOT NULL DEFAULT 'unemployed',
 job_grade INT UNSIGNED NOT NULL DEFAULT 0,
 position LONGTEXT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS nx_transactions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 player_id BIGINT UNSIGNED NOT NULL,
 account ENUM('cash','bank') NOT NULL,
 amount BIGINT NOT NULL,
 reason VARCHAR(100) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX (player_id),
 CONSTRAINT fk_nx_transactions_player FOREIGN KEY (player_id) REFERENCES nx_players(id) ON DELETE CASCADE
) ENGINE=InnoDB;
